using System.ComponentModel;

namespace BgOptimizer.Localization;

/// <summary>
/// Singleton translation table. XAML binds to it via indexer bindings
/// (e.g. Path=[Btn_Refresh]); switching Language raises a PropertyChanged
/// with an empty name, which WPF's binding engine treats as "re-evaluate
/// every binding on this source" — including indexer bindings — so the
/// whole UI updates without restarting the app.
/// </summary>
public class Loc : INotifyPropertyChanged
{
    public static Loc Instance { get; } = new();

    public event PropertyChangedEventHandler? PropertyChanged;

    public record LanguageOption(string Code, string Name)
    {
        public override string ToString() => Name;
    }

    public static readonly LanguageOption[] Languages =
    {
        new("en", "English"),
        new("uk", "Українська"),
        new("es", "Español"),
        new("de", "Deutsch"),
        new("it", "Italiano"),
        new("pl", "Polski"),
        new("ru", "Русский"),
    };

    private string _language = "en";
    public string Language
    {
        get => _language;
        set
        {
            if (_language == value || !Strings.ContainsKey(value)) return;
            _language = value;
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(string.Empty));
        }
    }

    public string this[string key] =>
        Strings.TryGetValue(_language, out var dict) && dict.TryGetValue(key, out var value)
            ? value
            : Strings["en"].GetValueOrDefault(key, key);

    public string Format(string key, params object[] args) => string.Format(this[key], args);

